/* ============================================================
   PHOTO STACK — swipeable stacked photo deck (loops through 18 photos
   using 3 reused DOM nodes for depth-0/1/2, rather than 18 live nodes)
   ============================================================ */
function initPhotoStack(){
  const stage = $('#stackStage');
  if(!stage) return;
  const counterEl = $('#stackCounter');
  const arrowLeft = $('#stackArrowLeft');
  const arrowRight = $('#stackArrowRight');
  const wrap = $('#stackNextWrap');

  const PHOTOS = [];
  for(let i=1;i<=18;i++){
    PHOTOS.push(`assets/images/stack/photo${String(i).padStart(2,'0')}.jpeg`);
  }

  const cardDepth0 = stage.querySelector('.depth-0');
  const cardDepth1 = stage.querySelector('.depth-1');
  const cardDepth2 = stage.querySelector('.depth-2');

  let index = 0;      // index of the photo currently on top
  let animating = false;
  let startX = 0, startY = 0, dx = 0, dragging = false;

  function render(){
    cardDepth0.querySelector('img').src = PHOTOS[index % PHOTOS.length];
    cardDepth1.querySelector('img').src = PHOTOS[(index + 1) % PHOTOS.length];
    cardDepth2.querySelector('img').src = PHOTOS[(index + 2) % PHOTOS.length];
    if(counterEl) counterEl.textContent = `${(index % PHOTOS.length) + 1} / ${PHOTOS.length}`;
  }

  function revealNext(){
    if(wrap && !wrap.querySelector('button')){
      const btn = document.createElement('button');
      btn.className = 'btn tap';
      btn.textContent = 'Next ➜';
      btn.addEventListener('click', () => goToPage('sing-intro'));
      wrap.appendChild(btn);
      gsapFadeIn(btn);
    }
  }

  function commitSwipe(direction){
    if(animating) return;
    animating = true;
    cardDepth0.classList.remove('no-transition');
    cardDepth0.classList.add(direction === 'left' ? 'fly-left' : 'fly-right');
    setTimeout(() => {
      index = (index + 1) % PHOTOS.length;
      cardDepth0.classList.add('no-transition');
      cardDepth0.classList.remove('fly-left', 'fly-right');
      cardDepth0.style.transform = '';
      render();
      // force reflow so the no-transition snap-back is applied before we
      // re-enable transitions for the next drag/commit
      // eslint-disable-next-line no-unused-expressions
      cardDepth0.offsetHeight;
      cardDepth0.classList.remove('no-transition');
      animating = false;
      revealNext();
    }, 460);
  }

  function resetPosition(){
    cardDepth0.style.transform = '';
  }

  function onPointerDown(e){
    if(animating) return;
    dragging = true;
    startX = (e.touches ? e.touches[0].clientX : e.clientX);
    startY = (e.touches ? e.touches[0].clientY : e.clientY);
    cardDepth0.classList.add('no-transition');
  }
  function onPointerMove(e){
    if(!dragging) return;
    const x = (e.touches ? e.touches[0].clientX : e.clientX);
    const y = (e.touches ? e.touches[0].clientY : e.clientY);
    dx = x - startX;
    const dy = (y - startY) * 0.15;
    cardDepth0.style.transform = `translate(${dx}px, ${dy}px) rotate(${dx / 18}deg)`;
  }
  function onPointerUp(){
    if(!dragging) return;
    dragging = false;
    cardDepth0.classList.remove('no-transition');
    if(Math.abs(dx) > 70){
      commitSwipe(dx < 0 ? 'left' : 'right');
    } else {
      resetPosition();
    }
    dx = 0;
  }

  cardDepth0.addEventListener('mousedown', onPointerDown);
  window.addEventListener('mousemove', onPointerMove);
  window.addEventListener('mouseup', onPointerUp);
  cardDepth0.addEventListener('touchstart', onPointerDown, { passive:true });
  cardDepth0.addEventListener('touchmove', onPointerMove, { passive:true });
  cardDepth0.addEventListener('touchend', onPointerUp);

  arrowLeft.addEventListener('click', () => commitSwipe('left'));
  arrowRight.addEventListener('click', () => commitSwipe('right'));

  render();

  // expose a reset hook for the replay flow
  stage._resetStack = () => {
    index = 0;
    animating = false;
    dragging = false;
    dx = 0;
    cardDepth0.classList.remove('fly-left','fly-right','no-transition');
    cardDepth0.style.transform = '';
    render();
  };
}

